"""Load raw CSV files from GCS into native BigQuery tables.

The default table-to-file mappings match the CSV names generated by
`collect_seoul_data.py`.

Example:
    python scripts/load_gcs_to_bigquery.py

If an actual CSV file name differs, pass a table-to-file mapping. The option can
be repeated:
    --mapping sales=서울시_상권분석서비스_추정매출.csv

Existing tables are protected by default. Add `--replace` only when the Raw
tables should be replaced with the contents of the current CSV files.
"""

from __future__ import annotations

import argparse
from pathlib import PurePosixPath

from google.cloud import bigquery


DEFAULT_PROJECT_ID = "bonggeunj"
DEFAULT_BUCKET_NAME = "codeit-data15-practice-dion"
DEFAULT_GCS_PREFIX = "seoul_commercial/raw"

DEFAULT_TABLE_FILES = {
    "sales": "seoul_sales_2025.csv",
    "store": "seoul_store_2025.csv",
    "street_population": "seoul_s_population_2025.csv",
    "worker_population": "seoul_worker_population_raw.csv",
    "visitor_facility": "seoul_viatr_raw.csv",
    "trade_area_info": "seoul_store_info.csv",
    "region_rate": "seoul_region_rate_raw.csv",
}


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Load GCS CSV files into the BigQuery Raw dataset."
    )
    parser.add_argument(
        "--project",
        default=DEFAULT_PROJECT_ID,
        help=f"GCP project ID. Default: {DEFAULT_PROJECT_ID}",
    )
    parser.add_argument(
        "--bucket",
        default=DEFAULT_BUCKET_NAME,
        help=f"Source GCS bucket name. Default: {DEFAULT_BUCKET_NAME}",
    )
    parser.add_argument(
        "--dataset",
        default="seoul_commercial_raw",
        help="Destination BigQuery dataset. Default: seoul_commercial_raw",
    )
    parser.add_argument(
        "--prefix",
        default=DEFAULT_GCS_PREFIX,
        help=f"GCS object prefix. Default: {DEFAULT_GCS_PREFIX}",
    )
    parser.add_argument(
        "--location",
        default="asia-northeast3",
        help="BigQuery dataset location. Default: asia-northeast3",
    )
    parser.add_argument(
        "--mapping",
        action="append",
        metavar="TABLE=FILE.csv",
        help=(
            "Override a table-to-file mapping. Repeat this option for multiple "
            "tables. When omitted, the seven default mappings are used."
        ),
    )
    parser.add_argument(
        "--replace",
        action="store_true",
        help="Replace existing destination tables using WRITE_TRUNCATE.",
    )
    return parser.parse_args()


def build_table_files(mapping_args: list[str] | None) -> dict[str, str]:
    if not mapping_args:
        return DEFAULT_TABLE_FILES.copy()

    table_files: dict[str, str] = {}
    for mapping in mapping_args:
        table_name, separator, file_name = mapping.partition("=")
        table_name = table_name.strip()
        file_name = file_name.strip()

        if not separator or not table_name or not file_name:
            raise ValueError(
                f"Invalid mapping '{mapping}'. Use TABLE=FILE.csv format."
            )
        if not file_name.lower().endswith(".csv"):
            raise ValueError(f"The mapped source must be a CSV file: {file_name}")

        table_files[table_name] = file_name

    return table_files


def main() -> None:
    args = parse_args()
    table_files = build_table_files(args.mapping)
    client = bigquery.Client(project=args.project, location=args.location)

    dataset_id = f"{args.project}.{args.dataset}"
    dataset = bigquery.Dataset(dataset_id)
    dataset.location = args.location
    client.create_dataset(dataset, exists_ok=True)

    write_disposition = (
        bigquery.WriteDisposition.WRITE_TRUNCATE
        if args.replace
        else bigquery.WriteDisposition.WRITE_EMPTY
    )
    prefix = args.prefix.strip("/")

    for table_name, file_name in table_files.items():
        object_name = str(PurePosixPath(prefix, file_name))
        source_uri = f"gs://{args.bucket}/{object_name}"
        table_id = f"{dataset_id}.{table_name}"

        job_config = bigquery.LoadJobConfig(
            source_format=bigquery.SourceFormat.CSV,
            skip_leading_rows=1,
            autodetect=True,
            encoding="UTF-8",
            write_disposition=write_disposition,
        )

        print(f"LOAD {source_uri} -> {table_id}")
        load_job = client.load_table_from_uri(
            source_uri,
            table_id,
            job_config=job_config,
            location=args.location,
        )
        load_job.result()

        table = client.get_table(table_id)
        print(f"DONE {table_id}: rows={table.num_rows}, columns={len(table.schema)}")

    print(f"Completed: loaded={len(table_files)} table(s)")


if __name__ == "__main__":
    main()
